const VISIBLE_COUNT = 20;

function starString(rating) {
  return "★".repeat(rating) + "☆".repeat(5 - rating);
}

export function initTestimonials() {
  const track = document.getElementById("testimonial-track");
  if (!track || reviews.length === 0) return;

  const shuffled = [...reviews];
  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const cardsHtml = shuffled
    .slice(0, VISIBLE_COUNT)
    .map(
      (review) => `
        <article class="testimonial-card">
          <p class="tracking-wide text-amber-400" aria-hidden="true">${starString(review.rating)}</p>
          <p class="mt-3 flex-1 text-slate-700">"${review.quote}"</p>
          <p class="mt-4 text-right text-sm font-semibold text-slate-400">— ${review.attribution}</p>
        </article>
      `
    )
    .join("");

  track.innerHTML = cardsHtml + cardsHtml;
  track.classList.add("is-scrolling");
}
